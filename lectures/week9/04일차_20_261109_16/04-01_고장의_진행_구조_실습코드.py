from pathlib import Path

import pandas as pd

df = pd.read_csv(Path(__file__).resolve().parent / "04-01_고장의_진행_구조_고장사례.csv")

print("사례 수:", len(df))
# 출력: 사례 수: 8


# ============================================================
# 실습 1 - 고장 사례를 P-F 곡선 위에 배치
# ============================================================
print("\n[실습 1] P-F 간격과 점검 주기")

리드타임 = 20  # 실습 1 가정: 확인·진단·조달·대기·작업에 20일 필요

# Step 2. 리드타임 안에 대응이 가능한지 판정
# PF간격이 리드타임보다 길어야 대응할 수 있습니다
df["대응가능"] = df["PF간격_일"] > 리드타임

# Step 4. 절반 규칙 - 점검 주기는 P-F 간격의 절반 이하
df["권장점검주기_일"] = df["PF간격_일"] / 2

실습1 = df[["사례ID", "설비", "PF간격_일", "권장점검주기_일", "대응가능"]]
print(실습1.to_string(index=False))
# 출력:
# 사례ID    설비  PF간격_일  권장점검주기_일  대응가능
#   A1    모터      90      45.0  True
#   A2   급기팬      45      22.5  True
#   A3 공기압축기     120      60.0  True
#   A4   감속기       0       0.0 False
#   B1 유압 유닛      30      15.0  True
#   B2   가열로     180      90.0  True
#   B3  컨베이어       0       0.0 False
#   B4 롤러테이블      10       5.0 False

print("\n리드타임 20일 기준 대응 불가:",
      list(df.loc[~df["대응가능"], "사례ID"]))
# 출력: 리드타임 20일 기준 대응 불가: ['A4', 'B3', 'B4']

# 저장 주기가 절반 규칙을 만족하는지도 함께 확인합니다
# 저장 주기(분)를 일로 바꿔서 권장 점검 주기와 비교합니다
저장주기_일 = df["저장주기_분"] / (60 * 24)
df["저장주기_적정"] = (df["데이터저장여부"] == "Y") & (저장주기_일 <= df["권장점검주기_일"])
print("\n저장 주기가 절반 규칙을 만족하는 사례:",
      list(df.loc[df["저장주기_적정"], "사례ID"]))
# 출력: 저장 주기가 절반 규칙을 만족하는 사례: ['A1', 'A2', 'A3', 'B1', 'B4']


# ============================================================
# 실습 2 - 돌발/점진 분류와 관측 가능성 판정
# ============================================================
print("\n[실습 2] 판정 3문항 적용")

# Step 1. 판정 3문항
# Q1 열화 과정이 물리적으로 존재하는가
# Q2 P-F 간격이 리드타임보다 긴가
# Q3 해당 신호가 데이터에 저장되는가

열화없는_손상형태 = ["과부하 파단", "이물"]


def 판정(행, 리드타임):
    # Q1
    if 행["손상형태"] in 열화없는_손상형태:
        return "물리적 돌발"
    # Q2
    if 행["PF간격_일"] <= 리드타임:
        return "간격 부족형"
    # Q3
    if 행["데이터저장여부"] != "Y":
        return "측정 부재형"
    return "예측 가능형"


# 케이스 A - 리드타임 7일 현장
df["케이스A_판정"] = df.apply(판정, axis=1, 리드타임=7)
# 케이스 B - 리드타임 30일 현장
df["케이스B_판정"] = df.apply(판정, axis=1, 리드타임=30)

실습2 = df[["사례ID", "설비", "손상형태", "PF간격_일",
            "데이터저장여부", "케이스A_판정", "케이스B_판정"]]
print(실습2.to_string(index=False))
# 출력:
# 사례ID    설비   손상형태  PF간격_일 데이터저장여부 케이스A_판정 케이스B_판정
#   A1    모터     마모      90       Y  예측 가능형  예측 가능형
#   A2   급기팬  오염 축적      45       Y  예측 가능형  예측 가능형
#   A3 공기압축기     마모     120       Y  예측 가능형  예측 가능형
#   A4   감속기 과부하 파단       0       N  물리적 돌발  물리적 돌발
#   B1 유압 유닛  경화 열화      30       Y  예측 가능형  간격 부족형
#   B2   가열로   열 열화     180       N  측정 부재형  측정 부재형
#   B3  컨베이어     이물       0       N  물리적 돌발  물리적 돌발
#   B4 롤러테이블  윤활 저하      10       Y  예측 가능형  간격 부족형

# Step 5. 리드타임 차이로 판정이 뒤집힌 사례 찾기
뒤집힘 = df[df["케이스A_판정"] != df["케이스B_판정"]]
print("\n리드타임 때문에 판정이 뒤집힌 사례:", list(뒤집힘["사례ID"]))
# 출력: 리드타임 때문에 판정이 뒤집힌 사례: ['B1', 'B4']

# Step 3. 예측 가능형만 모아 목표 조기 경보 시점 정하기
# 목표 경보 시점은 리드타임보다 길고 P-F 간격보다는 짧아야 합니다
가능 = df[df["케이스A_판정"] == "예측 가능형"].copy()
가능["목표경보_일전"] = (가능["PF간격_일"] * 0.5).round().astype(int)
print("\n케이스 A 예측 가능형의 목표 경보 시점")
print(가능[["사례ID", "설비", "PF간격_일", "목표경보_일전"]].to_string(index=False))
# 출력:
# 사례ID    설비  PF간격_일  목표경보_일전
#   A1    모터      90       45
#   A2   급기팬      45       22
#   A3 공기압축기     120       60
#   B1 유압 유닛      30       15
#   B4 롤러테이블      10        5

# Step 4. 예측 불가 사례의 대응 방향
대응표 = {
    "물리적 돌발": "이중화 또는 정기 교체",
    "간격 부족형": "보호 로직 또는 자동 정지",
    "측정 부재형": "계측 개선 또는 저장 주기 조정",
}
불가 = df[df["케이스B_판정"] != "예측 가능형"].copy()
불가["대응방향"] = 불가["케이스B_판정"].map(대응표)
print("\n케이스 B 예측 불가 사례의 대응 방향")
print(불가[["사례ID", "설비", "케이스B_판정", "대응방향"]].to_string(index=False))
# 출력:
# 사례ID    설비 케이스B_판정              대응방향
#   A4   감속기  물리적 돌발      이중화 또는 정기 교체
#   B1 유압 유닛  간격 부족형    보호 로직 또는 자동 정지
#   B2   가열로  측정 부재형 계측 개선 또는 저장 주기 조정
#   B3  컨베이어  물리적 돌발      이중화 또는 정기 교체
#   B4 롤러테이블  간격 부족형    보호 로직 또는 자동 정지
